CREATE TABLE organization (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL
);

CREATE TABLE event (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES organization(id),
  name text NOT NULL,
  venue text NOT NULL,
  teardown_deadline timestamptz NOT NULL
);

CREATE TABLE intake_draft (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id bigint NOT NULL REFERENCES event(id),
  status text NOT NULL CHECK (status IN ('PROCESSING', 'READY', 'FAILED', 'CONFIRMED')),
  stage text CHECK (stage IN ('ESTIMATE', 'SEGMENT')),
  failure_message text,
  created_at timestamptz NOT NULL
);

CREATE TABLE intake_draft_line (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  draft_id bigint NOT NULL REFERENCES intake_draft(id),
  category text NOT NULL CHECK (category IN ('DISPLAY_RACK', 'STORAGE_BIN', 'FOLDING_TABLE', 'UNKNOWN')),
  label text NOT NULL,
  count integer NOT NULL,
  boxes jsonb NOT NULL,
  width_cm integer,
  depth_cm integer,
  height_cm integer,
  condition text NOT NULL CHECK (condition IN ('GOOD', 'FAIR', 'POOR')),
  confidence numeric NOT NULL,
  needs_review boolean NOT NULL,
  CHECK (count >= 0),
  CHECK (confidence BETWEEN 0 AND 1),
  CHECK (width_cm > 0),
  CHECK (depth_cm > 0),
  CHECK (height_cm > 0),
  CHECK ((width_cm IS NULL AND depth_cm IS NULL AND height_cm IS NULL)
      OR (width_cm IS NOT NULL AND depth_cm IS NOT NULL AND height_cm IS NOT NULL))
);

CREATE TABLE item (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id bigint NOT NULL REFERENCES event(id),
  organization_id bigint NOT NULL REFERENCES organization(id),
  intake_draft_id bigint REFERENCES intake_draft(id),
  category text NOT NULL CHECK (category IN ('DISPLAY_RACK', 'STORAGE_BIN', 'FOLDING_TABLE')),
  label text NOT NULL,
  width_cm integer NOT NULL CHECK (width_cm > 0),
  depth_cm integer NOT NULL CHECK (depth_cm > 0),
  height_cm integer NOT NULL CHECK (height_cm > 0),
  condition text NOT NULL CHECK (condition IN ('GOOD', 'FAIR', 'POOR')),
  total_qty integer NOT NULL,
  available_qty integer NOT NULL,
  pickup_deadline timestamptz NOT NULL,
  vehicle_requirement text CHECK (vehicle_requirement IN ('SEDAN', 'SUV', 'VAN', 'TRUCK_1T')),
  conditions_transcript text,
  CHECK (total_qty >= 0),
  CHECK (available_qty >= 0 AND available_qty <= total_qty)
);

CREATE TABLE pickup_request (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id bigint NOT NULL REFERENCES organization(id),
  category text NOT NULL CHECK (category IN ('DISPLAY_RACK', 'STORAGE_BIN', 'FOLDING_TABLE')),
  quantity integer NOT NULL,
  vehicle_type text NOT NULL CHECK (vehicle_type IN ('SEDAN', 'SUV', 'VAN', 'TRUCK_1T')),
  pickup_deadline timestamptz,
  purpose text,
  transcript text,
  created_at timestamptz NOT NULL,
  CHECK (quantity > 0)
);

CREATE TABLE reservation (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id bigint NOT NULL REFERENCES pickup_request(id),
  item_id bigint NOT NULL REFERENCES item(id),
  organization_id bigint NOT NULL REFERENCES organization(id),
  quantity integer NOT NULL,
  handed_over_qty integer,
  status text NOT NULL CHECK (status IN ('HELD', 'CONFIRMED', 'HANDED_OVER', 'RELEASED', 'EXPIRED')),
  hold_expires_at timestamptz NOT NULL,
  pickup_deadline timestamptz NOT NULL,
  created_at timestamptz NOT NULL,
  CHECK (quantity > 0),
  CHECK (handed_over_qty >= 0 AND handed_over_qty <= quantity),
  CHECK (hold_expires_at <= pickup_deadline),
  CHECK ((status = 'HANDED_OVER') = (handed_over_qty IS NOT NULL))
);

CREATE TABLE reservation_transition (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reservation_id bigint NOT NULL REFERENCES reservation(id),
  from_status text CHECK (from_status IN ('HELD', 'CONFIRMED', 'HANDED_OVER', 'RELEASED', 'EXPIRED')),
  to_status text NOT NULL CHECK (to_status IN ('HELD', 'CONFIRMED', 'HANDED_OVER', 'RELEASED', 'EXPIRED')),
  actor text NOT NULL CHECK (actor IN ('AGENT', 'USER', 'SCHEDULER', 'HANDOVER')),
  at timestamptz NOT NULL
);

CREATE TABLE handover_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reservation_id bigint NOT NULL REFERENCES reservation(id),
  expected_qty integer NOT NULL,
  counted_qty integer NOT NULL,
  accepted_qty integer,
  status text NOT NULL CHECK (status IN ('COMPLETED', 'MISMATCH')),
  boxes jsonb NOT NULL,
  created_at timestamptz NOT NULL,
  CHECK (expected_qty > 0),
  CHECK (counted_qty >= 0),
  CHECK (accepted_qty >= 0 AND accepted_qty <= expected_qty),
  CHECK (status = 'MISMATCH' OR accepted_qty IS NOT NULL)
);

CREATE TABLE idempotency_record (
  idempotency_key uuid PRIMARY KEY,
  fingerprint text NOT NULL,
  state text NOT NULL CHECK (state IN ('IN_PROGRESS', 'DONE')),
  response_status integer,
  response_body jsonb,
  created_at timestamptz NOT NULL
);

